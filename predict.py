#!/usr/bin/env python3
"""Single-image prediction using a saved ResNet-50 model.

Requires the weights generated by train.py and CT images downloaded
separately. Educational use only; not a clinical diagnostic tool.
"""

import torch
import torch.nn as nn
import torchvision.models as models
import cv2
import os
from torchvision import transforms
from PIL import Image

ROOT_FOLDER = "CT-Scan images"
MODEL_PATH = "resnet50_lung_cancer_binary_detector_training.pth"
subfolders = ["Cancerous raw images - jpg", "Non-Cancerous raw images - jpg"]
IMG_SIZE = 224

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

#Load the trained model
model = models.resnet50(pretrained= False)
model.fc = nn.Linear(model.fc.in_features, 2) #Binary: cancer/non-cancer
model.load_state_dict(torch.load(MODEL_PATH, map_location = device))
model.to(device)
model.eval()

print("Model loaded successfully\n")

#Image preprocessing
transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize([0.5,0.5,0.5], [0.5,0.5,0.5])
])

#predict function
def predict_image(image_path):
    img=cv2.imread(image_path)
    if img is None:
        print("Error: could not read image.")
        return

    img = cv2.cvtColor(img,cv2.COLOR_BGR2RGB)
    img = cv2.resize(img,(IMG_SIZE,IMG_SIZE))

    img = Image.fromarray(img)
    img = transform(img).unsqueeze(0)
    img = img.to(device)

#prediction
    with torch.no_grad():
        outputs = model(img)
        probs = torch.softmax(outputs, dim=1)
        predicted_class = torch.argmax(probs, dim=1).item()
        confidence = probs[0][predicted_class].item()

    label = "PREDICTED CANCEROUS" if predicted_class == 1 else "PREDICTED NON-CANCEROUS"
    return label, confidence

#Choose picture

print("\nLUNG CANCER DETECTION SYSTEM\n")
print("-" * 120)
print(f"NOTE: THIS IS AN EXPERIMENTAL AI PROJECT. IF YOU HAVE SYMPTOMS OR CONCERNS, PLEASE CONSULT A DOCTOR.\nDO NOT RELY ON AI AS A SUBSTITUTE FOR PROFESSIONAL MEDICAL ADVICE.")
print("-" * 120)
try:
    user_input = int(input("Choose the subfolder (0=cancerous, 1=non-cancerous, 2=quit): "))
except ValueError:
    raise SystemExit("Please enter a number (0, 1, or 2).")

if user_input == 2:
    raise SystemExit(0)
if user_input not in (0, 1):
    raise SystemExit("Invalid folder selection.")
chosen_folder = os.path.join(ROOT_FOLDER, subfolders[user_input])
if not os.path.isdir(chosen_folder):
    raise SystemExit(f"Image folder not found: {chosen_folder}")
images = sorted(f for f in os.listdir(chosen_folder) if f.lower().endswith((".jpg", ".jpeg", ".png")))
if not images:
    raise SystemExit(f"No supported images found in {chosen_folder}")
print("\nImages available:")
for i, img_name in enumerate(images, 1):
    print(f"{i}: {img_name}")
try:
    img_choice = int(input("\nSelect image number: ")) - 1
except ValueError:
    raise SystemExit("Please enter a valid image number.")
if not 0 <= img_choice < len(images):
    raise SystemExit("Image selection out of range.")
image_path = os.path.join(chosen_folder, images[img_choice])

# Run prediction
label, confidence = predict_image(image_path)

print(f"Prediction: {label}")
print(f"Confidence: {confidence * 100:.2f}%")

print(f"Image: {images[img_choice]}")
img = cv2.imread(image_path)
label_text = f"{label} ({confidence*100:.2f}%)"
cv2.putText(img, label_text, (10, 40),
            cv2.FONT_HERSHEY_PLAIN, 1,
            (0, 255, 255), 2, cv2.LINE_AA)
img = cv2.cvtColor(img,cv2.COLOR_BGR2RGB)
cv2.imshow("Selected Image:", img)
cv2.waitKey(0)
cv2.destroyAllWindows()